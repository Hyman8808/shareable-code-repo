const TABLE = {}
PAIRS.split(' ').forEach((p) => {
  if (p.length === 2) TABLE[p[0]] = p[1]
})

const cache = {}

/** 转换一段文本；空白或空值原样返回 */
function convert(text) {
  if (!text) return text
  const s = String(text)
  if (cache[s] !== undefined) return cache[s]
  let out = ''
  for (let i = 0; i < s.length; i++) {
    const c = s.charAt(i)
    out += TABLE[c] || c
  }
  if (Object.keys(cache).length < 2048) cache[s] = out
  return out
}

